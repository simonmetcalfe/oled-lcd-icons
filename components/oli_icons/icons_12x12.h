/**
 * -------------------------------------------------------------------------------------------------
 * ICONS 12x12 - namespace oli::icons_12x12
 *
 * 1 bpp bitmaps, two bytes per row (the last 4 bits are padding), MSB = leftmost pixel.
 * Same format as Adafruit_GFX::drawBitmap() and ESPHome 1-bit images.
 *
 *   namespace ic = oli::icons_12x12;
 *   display.drawBitmap(x, y, ic::lock, ic::W, ic::H, SSD1306_WHITE);  // Arduino, Adafruit GFX
 *   oli::draw(it, x, y, ic::lock, ic::W, ic::H);                      // ESPHome display lambda
 *
 * Strokes are 1 px. Icons are centred on column 5 and leave column 11 blank, so icons drawn side by
 * side have a 1 px gap. Upright objects (plug, hourglass, home, lock, unlock, airplane, plant, water
 * drop, faucet, cup, music, flag, bulbs, cat, doors, motion), the tank levels, the rotate arrows and
 * the up/down arrows use all 12 rows. The rest sit on rows 0-10, centred on row 5.
 *
 * Sets list levels lowest first. For a 0-100 value:
 *   oli::frame(ic::wifiSet, oli::levelIndex(percent, ic::wifiLevels))
 * -------------------------------------------------------------------------------------------------
 */

